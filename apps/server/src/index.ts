import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { defaultWebRoot } from './static';
import { createGameServer } from './server';
if(process.env.NODE_ENV==='production'&&!existsSync(join(defaultWebRoot,'index.html')))throw new Error('Frontend build missing: run npm run build before npm start');
const {http,io}=createGameServer();
const port=Number(process.env.PORT??3001);
http.listen(port,'0.0.0.0',()=>{const address=http.address();console.log('server listening on :'+(address&&typeof address==='object'?address.port:port));});
const shutdown=()=>{io.close(()=>http.close());};
process.on('SIGTERM',shutdown);process.on('SIGINT',shutdown);
